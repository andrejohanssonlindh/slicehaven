export const SKILL_BY_ID: Map<string, SkillDef> = new Map(SKILLS.map((s) => [s.id, s]));

/** Skills that only attuned characters can have (everything mystic except Ceremony). */
export function needsAttunement(id: string): boolean {
  const s = SKILL_BY_ID.get(id);
  return !!s && s.group === 'mystik' && id !== 'Ceremoni';
}

/** Unknown specialist names (written in by the player or the data) get a generic entry. */
export function skillDef(id: string): SkillDef | undefined {
  const known = SKILL_BY_ID.get(id);
  if (known) return known;
  const m = /^([EFHK]):(.+)$/.exec(id);
  if (m) return { id, en: m[2], group: m[1] as SpecialKind, base: 0 };
  return undefined;
}
