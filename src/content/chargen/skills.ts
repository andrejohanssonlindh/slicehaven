/**
 * Skill catalogue for the character creator.
 * Keys are the source terms (Swedish) so the data files read like the rulebook's
 * own tables; `en` is what the UI shows. Base value 0 or 1 ("grundvärde").
 */
export type SkillGroup = 'kunskap' | 'mystik' | 'rorelse' | 'social' | 'strid' | 'vildmark';
export type SpecialKind = 'E' | 'F' | 'H' | 'K';

export interface SkillDef {
  id: string;
  en: string;
  group: SkillGroup | SpecialKind;
  base: 0 | 1;
}

type Row = [sv: string, en: string, base?: 0 | 1];

function rows(group: SkillGroup | SpecialKind, list: Row[], defBase: 0 | 1): SkillDef[] {
  return list.map(([sv, en, base]) => ({ id: group.length === 1 ? `${group}:${sv}` : sv, en, group, base: base ?? defBase }));
}

